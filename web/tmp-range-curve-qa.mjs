import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true })
const baseUrl = process.env.QA_BASE_URL ?? 'http://127.0.0.1:4173'
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('console', (message) => { if (message.type() === 'error') errors.push(`console: ${message.text()}`) })
page.on('pageerror', (error) => errors.push(`pageerror: ${error.message}`))
await page.goto(`${baseUrl}/?qa=range-curve`, { waitUntil: 'networkidle' })

const chooseLine = async (name) => {
  await page.getByRole('button', { name: 'Line tools' }).click()
  await page.getByRole('menu', { name: 'Line tools menu' }).getByRole('menuitem', { name, exact: true }).click()
}
const chooseRange = async (name) => {
  await page.getByRole('button', { name: 'Range tools' }).click()
  await page.getByRole('menu', { name: 'Range tools menu' }).getByRole('menuitem', { name, exact: true }).click()
}
const canvasSignature = () => page.locator('canvas').evaluateAll((canvases) => canvases.map((canvas) => canvas.toDataURL()).join('|'))

await page.getByRole('button', { name: 'Range tools' }).click()
assert.deepEqual(await page.getByRole('menu', { name: 'Range tools menu' }).getByRole('menuitem').allTextContents(), ['Price Range', 'Date Range', 'Date and Price Range'])
await page.keyboard.press('Escape')

await chooseLine('Curve')
await page.mouse.click(300, 600)
await page.mouse.click(520, 260)
await page.mouse.click(760, 460)
const curveToolbar = page.getByRole('toolbar', { name: 'Selected Curve drawing' })
await curveToolbar.waitFor()
await curveToolbar.getByRole('button', { name: 'Drawing properties' }).click()
const curveDialog = page.getByRole('dialog', { name: 'Edit curve drawing' })
await curveDialog.waitFor()
assert.deepEqual(await curveDialog.getByRole('tab').allTextContents(), ['Style', 'Coordinates', 'Visibility'])
await curveDialog.getByRole('tab', { name: 'Coordinates' }).click()
assert.equal(await curveDialog.getByRole('spinbutton', { name: /Point \d+ price/ }).count(), 3)
await curveDialog.getByRole('tab', { name: 'Style' }).click()
const beforeCurveStyle = await canvasSignature()
await curveDialog.getByRole('checkbox', { name: 'Background' }).click()
await page.waitForTimeout(80)
assert.notEqual(await canvasSignature(), beforeCurveStyle)
await curveDialog.screenshot({ path: '/tmp/curve-properties.png' })
const curveBeforeDrag = await curveDialog.boundingBox()
assert(curveBeforeDrag)
const moveHandle = curveDialog.getByRole('button', { name: 'Move drawing properties' })
await moveHandle.hover()
await page.mouse.down()
await page.mouse.move(curveBeforeDrag.x + 140, curveBeforeDrag.y + 100)
await page.mouse.up()
assert.notDeepEqual(await curveDialog.boundingBox(), curveBeforeDrag)
await curveDialog.getByRole('button', { name: 'Ok' }).click()

await chooseRange('Price Range')
await page.mouse.move(340, 300)
await page.mouse.down()
await page.mouse.move(680, 570, { steps: 8 })
await page.mouse.up()
const priceToolbar = page.getByRole('toolbar', { name: 'Selected Price Range drawing' })
await priceToolbar.waitFor()
assert.equal(await priceToolbar.getByRole('button', { name: 'Drawing fill' }).count(), 1)
assert.equal(await priceToolbar.getByRole('button', { name: 'Drawing text' }).count(), 1)
await priceToolbar.getByRole('button', { name: 'Drawing properties' }).click()
const priceDialog = page.getByRole('dialog', { name: 'Edit price-range drawing' })
await priceDialog.waitFor()
assert.deepEqual(await priceDialog.getByRole('tab').allTextContents(), ['Style', 'Text', 'Coordinates', 'Visibility'])
await priceDialog.getByRole('button', { name: 'Range statistics' }).click()
assert.deepEqual(await page.getByRole('menu', { name: 'Range statistics menu' }).getByRole('checkbox').evaluateAll((boxes) => boxes.map((box) => box.parentElement?.textContent?.trim())), ['Price range', 'Percent change', 'Change in pips'])
const priceSignature = await canvasSignature()
await page.getByRole('menu', { name: 'Range statistics menu' }).getByRole('checkbox', { name: 'Percent change' }).click()
await page.waitForTimeout(80)
assert.notEqual(await canvasSignature(), priceSignature)
await priceDialog.screenshot({ path: '/tmp/price-range-properties.png' })
await priceDialog.getByRole('button', { name: 'Ok' }).click()

await chooseRange('Date Range')
await page.mouse.move(420, 320)
await page.mouse.down()
await page.mouse.move(800, 590, { steps: 8 })
await page.mouse.up()
const dateToolbar = page.getByRole('toolbar', { name: 'Selected Date Range drawing' })
await dateToolbar.waitFor()
await dateToolbar.getByRole('button', { name: 'Drawing properties' }).click()
const dateDialog = page.getByRole('dialog', { name: 'Edit date-range drawing' })
await dateDialog.waitFor()
await dateDialog.getByRole('button', { name: 'Range statistics' }).click()
assert.deepEqual(await page.getByRole('menu', { name: 'Range statistics menu' }).getByRole('checkbox').evaluateAll((boxes) => boxes.map((box) => box.parentElement?.textContent?.trim())), ['Bars range', 'Date/time range', 'Volume'])
await dateDialog.screenshot({ path: '/tmp/date-range-properties.png' })
await page.screenshot({ path: '/tmp/range-curve-final.png', fullPage: true })

const mobile = await browser.newPage({ viewport: { width: 375, height: 812 } })
mobile.on('console', (message) => { if (message.type() === 'error') errors.push(`mobile console: ${message.text()}`) })
mobile.on('pageerror', (error) => errors.push(`mobile pageerror: ${error.message}`))
await mobile.goto(`${baseUrl}/?qa=range-curve-mobile`, { waitUntil: 'networkidle' })
const hidePanel = mobile.getByRole('button', { name: 'Hide operations panel' })
if (await hidePanel.count()) await hidePanel.click()
await mobile.getByRole('button', { name: 'Range tools' }).click()
const mobileMenu = mobile.getByRole('menu', { name: 'Range tools menu' })
const mobileBox = await mobileMenu.boundingBox()
assert(mobileBox && mobileBox.x >= 0 && mobileBox.x + mobileBox.width <= 375 && mobileBox.y >= 0 && mobileBox.y + mobileBox.height <= 812)

assert.deepEqual(errors, [])
console.log(JSON.stringify({ result: 'pass', curvePoints: 3, rangeTools: 3, priceStats: 3, dateStats: 3, liveSync: true, draggable: true, mobileBox, consoleErrors: 0 }, null, 2))
await browser.close()
