import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true })
const baseUrl = process.env.QA_BASE_URL ?? 'http://127.0.0.1:4173'
const errors = []
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
page.on('pageerror', (error) => errors.push(error.message))

await page.goto(`${baseUrl}/?qa=standard-drawing-properties`, { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Text and notes' }).click()
await page.getByRole('menu', { name: 'Text and notes menu' }).getByRole('menuitem', { name: 'Callout' }).click()
await page.mouse.click(320, 650)
await page.mouse.click(610, 360)

const toolbar = page.getByRole('toolbar', { name: 'Selected Callout drawing' })
await toolbar.waitFor()
await toolbar.getByRole('button', { name: 'Drawing properties' }).click()
const dialog = page.getByRole('dialog', { name: 'Edit callout drawing' })
await dialog.waitFor()
assert.deepEqual(await dialog.getByRole('tab').allTextContents(), ['Style', 'Text', 'Coordinates', 'Visibility'])
assert.equal(await dialog.getByText('LINE & BORDER', { exact: true }).count() > 0, true)
assert.equal(await dialog.getByText('FILL', { exact: true }).count() > 0, true)

await dialog.getByRole('tab', { name: 'Text' }).click()
await dialog.getByRole('textbox', { name: 'Drawing text' }).fill('Standardized callout')
await dialog.getByRole('button', { name: 'Align text right' }).click()
await dialog.getByRole('tab', { name: 'Coordinates' }).click()
assert.equal(await dialog.getByRole('spinbutton', { name: /Point \d+ price/ }).count(), 2)
await dialog.getByRole('tab', { name: 'Visibility' }).click()
await page.waitForTimeout(150)
const visibilityBox = await dialog.boundingBox()
assert(visibilityBox)
assert.equal(Math.round(visibilityBox.width), 456)
assert.equal(await dialog.getByRole('tabpanel').evaluate((panel) => panel.scrollWidth <= panel.clientWidth), true)
await page.screenshot({ path: '/tmp/standard-callout-properties.png', fullPage: true })

const mobile = await browser.newPage({ viewport: { width: 375, height: 812 } })
mobile.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
mobile.on('pageerror', (error) => errors.push(error.message))
await mobile.goto(`${baseUrl}/?qa=standard-drawing-properties-mobile`, { waitUntil: 'networkidle' })
const hidePanel = mobile.getByRole('button', { name: 'Hide operations panel' })
if (await hidePanel.count()) await hidePanel.click()
await mobile.getByRole('button', { name: 'Text and notes' }).click()
await mobile.getByRole('menu', { name: 'Text and notes menu' }).getByRole('menuitem', { name: 'Callout' }).click()
await mobile.mouse.click(90, 600)
await mobile.mouse.click(250, 300)
const mobileToolbar = mobile.getByRole('toolbar', { name: 'Selected Callout drawing' })
await mobileToolbar.waitFor()
await mobileToolbar.getByRole('button', { name: 'Drawing properties' }).click()
const mobileDialog = mobile.getByRole('dialog', { name: 'Edit callout drawing' })
await mobileDialog.waitFor()
const mobileBox = await mobileDialog.boundingBox()
assert(mobileBox)
assert(mobileBox.x >= 0 && mobileBox.x + mobileBox.width <= 375)
assert(mobileBox.y >= 0 && mobileBox.y + mobileBox.height <= 812)
assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true)

assert.deepEqual(errors, [])
console.log(JSON.stringify({ result: 'pass', tabs: ['Style', 'Text', 'Coordinates', 'Visibility'], visibilityWidth: Math.round(visibilityBox.width), mobileBox, consoleErrors: 0 }, null, 2))
await browser.close()
